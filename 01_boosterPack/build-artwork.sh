#!/bin/bash
# Regenerates artwork.js <- ./artwork/*.png|jpg (embedded as base64).
# The tool opens by double-click (file://), where the browser does not let WebGL use
# images read from disk: embedding them is what makes the preloaded artwork work offline.
# Files with "front" in the name appear in the Front slot's "Artwork…" dropdown.
# Usage:  bash build-artwork.sh   (works from any location, macOS or Linux)
set -e
cd "$(dirname "$0")"
shopt -s nullglob nocaseglob
SRC="artwork"
if [ ! -d "$SRC" ]; then echo "Folder not found: $SRC"; exit 1; fi
n=0
{
  echo "// Generated by build-artwork.sh — do not edit by hand."
  echo "window.BP_ARTWORKS = ["
  for f in "$SRC"/*.png "$SRC"/*.jpg "$SRC"/*.jpeg; do
    name=$(basename "$f")
    case "${name##*.}" in [Pp][Nn][Gg]) mime="image/png";; *) mime="image/jpeg";; esac
    printf '  {"name":"%s","url":"data:%s;base64,' "$name" "$mime"
    base64 < "$f" | tr -d '\n'
    echo '"},'
    n=$((n+1))
  done
  echo "];"
} > artwork.js
echo "artwork.js: $n image(s) embedded"
